export function t(key, params = null) {
  let str = key;
  if (translations[currentLang] && translations[currentLang][key]) {
    str = translations[currentLang][key];
  } else if (HARD_FALLBACKS[key]) {
    str = HARD_FALLBACKS[key][currentLang] || HARD_FALLBACKS[key]['ru'] || HARD_FALLBACKS[key]['en'];
  } else if (translations['ru'] && translations['ru'][key]) {
    str = translations['ru'][key];
  } else if (translations['en'] && translations['en'][key]) {
    str = translations['en'][key];
  }

  if (params && typeof params === 'object') {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
  }
  return str;
}

export function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', lang);
    }
    try {
      localStorage.setItem('pc-builder-lang', lang);
    } catch (e) {}
  }
}

export function getCurrentLanguage() {
  return currentLang;
}

export function initI18n() {
  try {
    const saved = localStorage.getItem('pc-builder-lang');
    if (saved && translations[saved]) {
      currentLang = saved;
    }
  } catch (e) {}
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', currentLang);
  }
  return currentLang;
}
