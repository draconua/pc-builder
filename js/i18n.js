export function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (HARD_FALLBACKS[key]) {
    return HARD_FALLBACKS[key][currentLang] || HARD_FALLBACKS[key]['ru'] || HARD_FALLBACKS[key]['en'];
  }
  if (translations['ru'] && translations['ru'][key]) {
    return translations['ru'][key];
  }
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}

export function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    try {
      localStorage.setItem('pc-builder-lang', lang);
    } catch (e) {}
  }
}

export function getCurrentLanguage() {
  return currentLang;
}

export function initI18n() {
  try {
    const saved = localStorage.getItem('pc-builder-lang');
    if (saved && translations[saved]) {
      currentLang = saved;
    }
  } catch (e) {}
  return currentLang;
}
